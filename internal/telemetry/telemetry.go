// Package telemetry holds the OTLP export settings the vault and the workflow
// share: the switches, the log filters, the logger wiring and the optional
// otlp health dependency. Log export is default-deny: a field reaches the
// collector only if AllowFields names it.
package telemetry

import (
	"context"
	"errors"
	"io"
	"os"
	"regexp"
	"strings"

	"github.com/Bugs5382/go-buildinfo/health"
	log "github.com/Bugs5382/go-log"
	otel "github.com/Bugs5382/go-otel"
	"github.com/rs/zerolog"
	otelapi "go.opentelemetry.io/otel"
	"google.golang.org/grpc/status"
)

const (
	// EnvInsecureSkipVerify turns off certificate checks on the collector when
	// it is exactly "true".
	EnvInsecureSkipVerify = "OTLP_INSECURE_SKIP_VERIFY"
	// EnvLogsEnabled turns on log export when it is exactly "true".
	EnvLogsEnabled = "OTLP_LOGS_ENABLED"
)

// AllowFields are the log fields that may leave the box: ids, counts,
// durations, classes, states and short enums. Each value is set by this code
// or generated by it. Keep off the list anything that can hold a value, a name
// someone typed, a URL, an address, a body or a target system's text. That is
// why error, reason, subject, field_key, trigger, added, removed, version,
// commit, claimed_actor, panic and stack aren't here: each holds free text or
// caller input in at least one log call, or a fingerprint.
var AllowFields = []string{
	"action", "active_ref", "actor", "actor_user_id", "allowed", "attempt",
	"caller", "clamped", "confirm", "count", "cutoff", "decided_by",
	"dependencies", "dependency", "dev_static_kek_loaded", "end_reason",
	"error_class", "expires_at", "folder_id", "folders", "found",
	"from_target_id", "from_type_id", "heartbeat_opt_out", "item", "items",
	"lease_id", "method", "mode", "new_version_no", "otlp_code", "outcome",
	"parent_id", "port", "principal_id", "principal_kind", "request_id",
	"requested", "result", "retention_days", "retry_in", "reveals",
	"rewrapped_records", "rewrapped_versions", "rotated_by",
	"rotation_opt_out", "rpc", "run_id", "secret_id", "secrets", "session_id",
	"state", "target_id", "to_type_id", "token_id", "type_id",
	"use_id", "user_id", "value_version", "verb", "version_no", "worker_id",
}

var apiToken = regexp.MustCompile(`\bsnk_[A-Za-z0-9_\-]+`)

// Options are the settings for otel.InitWithOptions. With both switches unset
// they change nothing about what is exported.
func Options(getenv func(string) string) []otel.Option {
	return []otel.Option{
		otel.WithInsecureSkipVerify(getenv(EnvInsecureSkipVerify) == "true"),
		otel.WithLogs(logsEnabled(getenv)),
		otel.WithLogAllowFields(AllowFields...),
		otel.WithLogRedactPatterns(apiToken),
	}
}

func logsEnabled(getenv func(string) string) bool { return getenv(EnvLogsEnabled) == "true" }

// Output is what the service logs to: stdout, plus the export writer when logs
// are on. The export writer discards everything until otel init, so the logger
// can be built first. It only understands JSON lines, so LOG_FORMAT=console
// exports nothing.
func Output(getenv func(string) string) io.Writer {
	if !logsEnabled(getenv) {
		return os.Stdout
	}
	return io.MultiWriter(os.Stdout, otel.LogWriter())
}

// NewLoggers builds the service's two loggers over one Output.
func NewLoggers(service string, getenv func(string) string) (log.TraceLogger, zerolog.Logger) {
	lg := log.NewLoggerWithOptions(service, log.WithOutput(Output(getenv)))
	// go-log has no options on New; with no span in ctx, Ctx is the logger
	// NewLoggerWithOptions just built.
	return lg, log.Ctx(context.Background()) //nolint:staticcheck
}

// HandleErrors sends otel's internal errors to lg. The error text is left out
// because it can carry the endpoint and headers; only the gRPC code is kept.
func HandleErrors(lg log.Logger) {
	otelapi.SetErrorHandler(otelapi.ErrorHandlerFunc(func(err error) {
		lg.Warn("otel export error", log.F("otlp_code", status.Code(err).String()))
	}))
}

var errExportFailing = errors.New("otlp export failing")

// Dependencies is the optional otlp health dependency, or nothing when no
// endpoint is set. It never takes readiness down.
func Dependencies(endpoint string, getenv func(string) string) []health.Dependency {
	if strings.TrimSpace(endpoint) == "" {
		return nil
	}
	logs := logsEnabled(getenv)
	return []health.Dependency{{Name: "otlp", Check: func(context.Context) error {
		if exportDown(otel.ExportState(), logs) {
			return errExportFailing
		}
		return nil
	}}}
}

func exportDown(st otel.ExportStatus, logs bool) bool {
	return failing(st.Traces) || failing(st.Metrics) || (logs && failing(st.Logs))
}

func failing(s otel.SignalStatus) bool { return s.LastErrorAt.After(s.LastSuccess) }
